    private static void startGame() {
        movement = new Movement(board, bag, bag.getNextBlockQueue(), START_ROW, START_COL);
        controls = new Controls(panel);
        gameMechanics = new GameMechanics(board, frame);
        effectBag = new RandomizeEffects();
        effects = new ActiveEffects(new GameContext(board, movement, gameMechanics, panel, frame, bag));
        effects = new ActiveEffects(
        new GameContext(board, movement, gameMechanics, panel, frame, bag));
        effectsDisplay = new EffectsDisplay(frame, effects);
        effects.setOnApply(effectsDisplay::announce);
        objectives = new RandomizeObjectives();
        newObjective();
        queue = bag.getQueue();
        ghostDeadline = System.nanoTime() + GHOST_INTERVAL;
        
        for (int n = 0; n < 5; n++) {
            drawnQueue[n].setQueuePiece(queue[n]);
        }
        
        controls.bind("LEFT",  () -> movement.moveLeft());
        controls.bind("RIGHT", () -> movement.moveRight());
        controls.bind("DOWN",  () -> movement.softDrop());
        controls.bind("UP",    () -> movement.rotateClockwise());
        controls.bind("X",    () -> movement.rotateClockwise());
        controls.bind("Z",     () -> movement.rotateCounterClockwise());
        controls.bind("U",     () -> movement.rotate180());
        controls.bind("A",     () -> movement.rotate180());
        controls.bind("C",     () -> {
                movement.putHold();
                drawHoldPiece.setQueuePiece(movement.getHoldPiece());
                });
        controls.bind("SPACE", () -> {
            if (movement.hardDrop()) {
                lockAndSpawn(true);
            }
        });
        controls.bind("ESCAPE",   () -> togglePause());
        refresh();
        
        timer = new Timer(10, e -> {
            if (movement.applyGravity()) {
                lockAndSpawn(false);
            }
            if (System.nanoTime() - objectiveDeadline >= 0) {
                objectiveFailed();
            }
            long remainingNanos = objectiveDeadline - System.nanoTime();
            long secondsLeft = Math.max(0,
                    (remainingNanos + 999_999_999L) / 1_000_000_000L);
            frame.setObjectiveTime(secondsLeft);
            if (System.nanoTime() - ghostDeadline >= 0) {
                ghostManager.spawnGhost();
                ghostManager.setGhostSpeed(board.getLevel());
                ghostDeadline = System.nanoTime() + GHOST_INTERVAL;
            }    
            refresh();
            effects.update();
            effectsDisplay.update();
        });
        timer.start();
    }
    
    private static void lockAndSpawn(boolean hardDropped) {
        if (gameOver) {
            ghostManager.pause();
            return;
        }      
        movement.lockPiece();
        
        int linesBefore = board.getLinesCleared();
        int scoreBefore = GameMechanics.getScore();
        gameMechanics.clearLinesAndScore();
        LockEvent event = new LockEvent(board.getLinesCleared() - linesBefore,
                GameMechanics.getScore() - scoreBefore, movement.usedHold(), hardDropped);
        currentObjective.onLock(event);
        if (currentObjective.isComplete()) {
            objectiveCompleted();
        } else {
            showObjective();
        }
        
        Blocks next = bag.getNextBlockQueue();
        movement.returnHold();
        queue = bag.getQueue();
        
        for (int n = 0; n < 5; n++) {
            drawnQueue[n].setQueuePiece(queue[n]);
        }
        if (!movement.canSpawn(next, 0, (((board.getBoardWidth() + 1) / 2) - 
                ((next.getSize() + 1) / 2)))) {
            gameOver = true;
            panel.setCurrentPiece(null, 0, 0);
            timer.stop();
            System.out.println("Game over loser"); //debug, needs to be added to gui
            return;
        }
        movement.spawnNewPiece(next, 0, (((board.getBoardWidth() + 1) / 2) - 
                ((next.getSize() + 1) / 2)));
    }
    
    private static void togglePause() {                                         
        if (isPaused) {
            resumeGame();
        } else {
            pauseGame();
        }
    }
    
    private static void pauseGame() {
        timer.stop();
        ghostManager.pause();
        frame.pauseEffectPopup();
        effects.pause();
        controls.pauseControls(true);
        isPaused = true;
        lastPauseTime = System.nanoTime();
        showScreen("Pause");
    }
    
