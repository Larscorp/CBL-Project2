    public final void refreshScores() {
        java.util.List<Integer> scores = Scoreboard.load();
        javax.swing.JLabel[] labels = {scoreLabel1, scoreLabel2,
            scoreLabel3, scoreLabel4, scoreLabel5};
        for (int i = 0; i < labels.length; i++) {
            if (i < scores.size()) {
                labels[i].setText((i + 1) + ".  " + scores.get(i));
            } else {
                labels[i].setText((i + 1) + ".  -");
            }
        }
    }
